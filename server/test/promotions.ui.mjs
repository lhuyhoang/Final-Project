import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import path from 'node:path'
import os from 'node:os'

export async function runPromotionUI({ base, admin, customer, product, voucher, request, write }) {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    let cookie = admin
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const pageErrors = []
    page.on('pageerror', error => pageErrors.push(error.message))
    await page.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url())
      if (url.pathname === '/api/admin/stripe/overview') return route.fulfill({ json: { revenueSeries: [], recentPayments: [] } })
      const response = await fetch(base + url.pathname + url.search, { method: req.method(), headers: { 'Content-Type': 'application/json', cookie }, ...(req.postData() ? { body: req.postData() } : {}) })
      await route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() })
    })
    await page.goto('http://127.0.0.1:5173/admin')
    await page.locator('.admin-sidebar button').filter({ hasText: 'Khuyến mãi' }).click()
    await page.getByRole('heading', { name: 'Flash Sale', exact: true }).waitFor()
    await page.locator('.promo-product-list label').filter({ hasText: product.name }).getByRole('checkbox').check()
    const local = value => new Date(value - new Date(value).getTimezoneOffset() * 60000).toISOString().slice(0, 16)
    await page.locator('.promo-dates input').nth(0).fill(local(Date.now() - 60000))
    await page.locator('.promo-dates input').nth(1).fill(local(Date.now() + 3600000))
    await page.getByRole('button', { name: 'Lưu Flash Sale', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Đã lưu sản phẩm' }).waitFor()
    await page.reload()
    await page.locator('.promo-product-list label').filter({ hasText: product.name }).getByRole('checkbox').waitFor()
    assert.equal(await page.locator('.promo-product-list label').filter({ hasText: product.name }).getByRole('checkbox').isChecked(), true)
    await page.locator('.promo-create input').fill('120000')
    await page.getByRole('button', { name: 'Tạo mã ngẫu nhiên' }).click()
    await page.getByRole('status').filter({ hasText: 'Đã tạo mã' }).waitFor()
    const newCode = await page.locator('.promo-code b').first().innerText()
    assert.match(newCode, /^(?=.*[A-Z])(?=.*\d)[A-Z0-9]{10}$/)
    const row = page.locator('tr').filter({ hasText: newCode })
    await row.locator('input').fill('130000')
    await row.getByRole('button', { name: 'Lưu', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Đã cập nhật voucher' }).waitFor()
    assert.equal((await request('/api/admin/promotions', { cookie: admin })).data.vouchers.find(item => item.code === newCode).amount, 130000)
    await page.screenshot({ path: path.join(os.tmpdir(), 'quadpro-promotions-admin.png'), fullPage: true })
    await page.getByRole('button', { name: 'Chuyển sang giao diện tối', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.getByRole('button', { name: 'Lưu Flash Sale', exact: true }).evaluate(node => getComputedStyle(node).fontSize !== '0px'))
    assert.equal(await page.getByRole('button', { name: `Tắt voucher ${newCode}`, exact: true }).isVisible(), true)
    await page.screenshot({ path: path.join(os.tmpdir(), 'quadpro-promotions-mobile-dark.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('http://127.0.0.1:5173/')
    await page.locator('#deals').waitFor()
    assert.equal(await page.locator('#deals .product-card').count(), 1)
    assert.ok((await page.locator('#deals').innerText()).includes(product.name))
    const countdown = await page.locator('#deals .countdown').innerText()
    await page.waitForFunction(value => document.querySelector('#deals .countdown')?.innerText !== value, countdown)
    await write('/api/admin/promotions/flash-sale', { productIds: [] })
    await page.reload()
    await page.waitForResponse(response => response.url().includes('/api/settings'))
    assert.equal(await page.locator('#deals').count(), 0)
    const expiresSoon = { productIds: [product.id], startsAt: new Date(Date.now() - 60000).toISOString(), endsAt: new Date(Date.now() + 6000).toISOString() }
    await write('/api/admin/promotions/flash-sale', expiresSoon)
    await page.reload()
    await page.locator('#deals').waitFor()
    await page.locator('#deals').waitFor({ state: 'detached', timeout: 10000 })
    // Customer checkout: actual voucher validation/order endpoints, no gateway charges.
    cookie = customer
    await page.evaluate(item => localStorage.setItem('quadpro-cart', JSON.stringify([{ ...item, quantity: 1 }])), product)
    await page.goto('http://127.0.0.1:5173/checkout')
    await page.locator('#checkout-voucher-code').fill(newCode)
    await page.getByRole('button', { name: 'Áp dụng', exact: true }).click()
    await page.locator('.checkout-voucher-applied').waitFor()
    assert.ok((await page.locator('.summary-totals').innerText()).includes('870.000'))
    await page.locator('#checkout-name').fill('Test Customer')
    await page.locator('#checkout-phone').fill('0901234567')
    await page.locator('#checkout-address').fill('123 Test Street, Hanoi')
    await page.getByRole('button', { name: 'Tiếp tục' }).click()
    await page.getByRole('button', { name: 'Tiếp tục' }).click()
    assert.ok((await page.locator('.u042-confirm-total').innerText()).includes('870.000'))
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.u042-pane.on')).opacity) === 1)
    await page.screenshot({ path: path.join(os.tmpdir(), 'quadpro-checkout-voucher.png'), fullPage: true })
    const serverVoucher = (await request('/api/admin/promotions', { cookie: admin })).data.vouchers.find(item => item.code === newCode)
    await write(`/api/admin/vouchers/${serverVoucher.id}`, { amount: 130000, isActive: false })
    await page.getByRole('button', { name: 'Xác nhận đặt hàng' }).click()
    await page.locator('.u042-submit-error').filter({ hasText: 'Voucher' }).waitFor()
    await write(`/api/admin/vouchers/${serverVoucher.id}`, { amount: 130000, isActive: true })
    const orderResponse = page.waitForResponse(response => response.url().endsWith('/api/orders') && response.request().method() === 'POST')
    await page.getByRole('button', { name: 'Xác nhận đặt hàng' }).click()
    const result = await orderResponse
    assert.equal(result.status(), 201)
    assert.equal((await result.json()).total, 870000)
    assert.deepEqual(pageErrors, [])
    console.log('PASS UI: campaign selection/save/reload, random/edit voucher, dark/mobile layout, selected-only Flash Sale, real countdown/auto expiry/empty hide, checkout discount and disabled-code retry.')
  } finally { await browser.close() }
}
