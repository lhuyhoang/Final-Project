import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { readFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

export async function runAppearanceUI({ base, admin, staff, request, write }) {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    let cookie = admin
    page.on('pageerror', error => errors.push(error.message))
    const png = await readFile(new URL('../../client/public/images/brand/quadpro-logo.png', import.meta.url))
    await page.route('https://assets.example.test/**', route => route.fulfill({ contentType: 'image/png', body: png }))
    await page.route('https://api.cloudinary.com/v1_1/**', route => route.fulfill({ json: { secure_url: 'https://assets.example.test/uploaded-logo.png' } }))
    await page.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url())
      if (url.pathname === '/api/admin/stripe/overview') return route.fulfill({ json: { error: 'Not used in appearance tests' } })
      const response = await fetch(base + url.pathname + url.search, { method: req.method(), headers: { 'Content-Type': 'application/json', cookie }, ...(req.postData() ? { body: req.postData() } : {}) })
      await route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() })
    })
    await page.goto('http://127.0.0.1:5173/admin')
    await page.locator('.admin-sidebar nav button').filter({ hasText: 'Cài đặt' }).click()
    await page.locator('.settings-function-grid').waitFor()
    assert.equal(await page.locator('.settings-function-grid > button').count(), 4)
    assert.equal(await page.locator('.settings-function-grid .lucide-settings').count(), 4)
    const select = name => page.locator('.settings-function-grid > button').filter({ hasText: name }).click()
    await select('Hiệu ứng chuyển cảnh')
    await page.locator('.transition-playground').waitFor()
    assert.equal(await page.locator('.transition-hover-showcase').count(), 0)
    await page.getByRole('button', { name: 'Lưu hiệu ứng cửa hàng', exact: true }).click()
    await page.locator('.transition-save-notice').waitFor()
    await select('Hiệu ứng hover')
    await page.locator('input[name="hoverEffect"][value="lift"]').check()
    await page.locator('.settings-hover-duration input').evaluate(node => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(node, '650'); node.dispatchEvent(new Event('input', { bubbles: true })) })
    await page.getByRole('button', { name: 'Lưu hover', exact: true }).click()
    await page.locator('.settings-feedback.success').waitFor()
    assert.equal((await request('/api/settings')).data.appearance.hoverEffect, 'lift')
    assert.equal((await request('/api/settings')).data.appearance.hoverDurationMs, 650)
    await select('Thay đổi logo')
    await page.getByLabel('URL ảnh logo', { exact: true }).fill('javascript:alert(1)')
    await page.getByRole('button', { name: 'Lưu logo', exact: true }).click()
    await page.getByRole('alert').waitFor()
    await page.locator('.settings-upload input').setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: png })
    await page.getByRole('status').filter({ hasText: 'Đã tải ảnh lên' }).waitFor()
    await page.getByRole('button', { name: 'Lưu logo', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Đã lưu và áp dụng' }).waitFor()
    assert.equal(await page.locator('.admin-logo img').getAttribute('src'), 'https://assets.example.test/uploaded-logo.png')
    assert.equal(await page.locator('link[rel="icon"]').getAttribute('href'), 'https://assets.example.test/uploaded-logo.png')
    await page.reload()
    await page.getByLabel('URL ảnh logo', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('URL ảnh logo', { exact: true }).inputValue(), 'https://assets.example.test/uploaded-logo.png')
    await select('Thay đổi banner')
    for (const [index, image] of ['/images/banners/build-pc-gaming.jpg', '/images/banners/pc-delta-force.jpg'].entries()) {
      await page.getByRole('button', { name: 'Thêm banner', exact: true }).click()
      await page.getByLabel(`URL ảnh banner ${index + 1}`, { exact: true }).fill(image)
      await page.locator('.settings-banner-row').nth(index).getByLabel('Mô tả ảnh', { exact: true }).fill(`Test Banner ${index + 1}`)
    }
    await page.getByRole('button', { name: 'Đưa banner 2 lên', exact: true }).click()
    await page.getByLabel('Thời gian chuyển banner (giây)', { exact: true }).fill('2')
    await page.getByRole('button', { name: 'Lưu banner', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Đã lưu và áp dụng' }).waitFor()
    assert.equal((await request('/api/settings')).data.appearance.banners[0].label, 'Test Banner 2')
    await page.screenshot({ path: path.join(os.tmpdir(), 'quadpro-settings-banner.png'), fullPage: true })
    await page.getByRole('button', { name: 'Chuyển sang giao diện tối', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(os.tmpdir(), 'quadpro-settings-mobile-dark.png'), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('http://127.0.0.1:5173/')
    await page.locator('html[data-product-hover="lift"]').waitFor()
    assert.equal(await page.locator('.header-main .quadpro-brand-mark').getAttribute('src'), 'https://assets.example.test/uploaded-logo.png')
    assert.equal(await page.locator('footer .quadpro-brand-mark').getAttribute('src'), 'https://assets.example.test/uploaded-logo.png')
    assert.equal(await page.locator('.home-banners-slide').count(), 2)
    const first = await page.locator('.home-banners-slide.is-active img').getAttribute('src')
    await page.waitForFunction(image => document.querySelector('.home-banners-slide.is-active img')?.getAttribute('src') !== image, first)
    const card = page.locator('.product-card').first()
    await card.hover()
    await page.waitForFunction(() => new DOMMatrix(getComputedStyle(document.querySelector('.product-card')).transform).m42 < -4.9)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await card.evaluate(node => getComputedStyle(node).transform), 'none')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await write({ banners: [], hoverEffect: 'none' })
    await page.reload()
    await page.locator('html[data-product-hover="none"]').waitFor()
    assert.equal(await page.locator('.home-banners').count(), 0)
    await page.locator('.product-card').first().hover()
    assert.equal(await page.locator('.product-card .product-media > img').first().evaluate(node => getComputedStyle(node).transform), 'none')
    cookie = staff
    await page.goto('http://127.0.0.1:5173/admin')
    await page.locator('.settings-function-grid').waitFor()
    assert.equal(await page.locator('.admin-sidebar nav > button').count(), 1)
    assert.ok((await page.locator('.admin-sidebar nav').innerText()).includes('Cài đặt'))
    assert.deepEqual(errors, [])
    console.log('PASS UI: four gear settings, preserved transitions, save/reload hover/logo/favicon, mocked upload, banner order/interval/empty hide, live product hover/reduced motion, dark mobile and settings-only staff.')
  } finally { await browser.close() }
}
