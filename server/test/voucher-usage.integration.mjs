import assert from 'node:assert/strict'

export async function testVoucherUsage({ db, request, write, login, passwordHash, product, extra, customer, fake }) {
  const shoppers = []
  for (let i = 0; i < 5; i++) {
    const user = await db.createUser({ name: `Voucher Shopper ${i}`, email: `voucher-shopper-${i}@example.com`, passwordHash, role: 'customer' })
    shoppers.push({ user, cookie: await login(user.email) })
  }
  const create = async body => { const result = await write('/api/admin/vouchers', { amount: 100000, ...body }, 'POST'); assert.equal(result.status, 201); return result.data }
  const body = code => ({ items: [{ productId: product.id, quantity: 1 }], customer: { name: 'Voucher Customer', phone: '0901234567' }, shipping: { address: '123 Voucher Street, Hanoi' }, voucherCode: code })
  const checkout = (code, cookie = customer, path = '/api/orders', productId = product.id) => request(path, { cookie, method: 'POST', body: { ...body(code), items: [{ productId, quantity: 1 }] } })
  const preview = (code, cookie = customer) => request('/api/vouchers/validate', { cookie, method: 'POST', body: { code, subtotal: product.price } })
  const listed = async code => (await db.listVouchers()).find(voucher => voucher.code === code)
  const expiresAt = new Date(Date.now() + 86400000).toISOString()
  const limited = await create({ maxUses: 2, expiresAt })
  assert.equal(limited.maxUses, 2)
  assert.equal(limited.expiresAt, expiresAt)
  assert.equal((await preview(limited.code, shoppers[0].cookie)).status, 200)
  const stock = (await db.findProductById(product.id)).stock
  const first = await checkout(limited.code, shoppers[0].cookie)
  assert.equal(first.status, 201)
  assert.equal((await preview(limited.code, shoppers[0].cookie)).status, 400)
  assert.equal((await checkout(limited.code, shoppers[0].cookie)).status, 400)
  assert.equal((await db.findProductById(product.id)).stock, stock - 1, 'Rejected reuse does not consume inventory')
  assert.equal((await checkout(limited.code, shoppers[1].cookie)).status, 201)
  assert.equal((await checkout(limited.code, shoppers[2].cookie)).status, 400)
  assert.equal((await listed(limited.code)).usedCount, 2)
  assert.equal((await write(`/api/admin/vouchers/${limited.id}`, { maxUses: 1 })).status, 409)
  assert.equal((await write(`/api/admin/vouchers/${limited.id}`, { maxUses: 3 })).status, 200)
  assert.equal((await checkout(limited.code, shoppers[2].cookie)).status, 201)
  assert.equal((await write(`/api/admin/vouchers/${limited.id}`, { expiresAt: new Date(Date.now() - 1000).toISOString() })).status, 200)
  assert.equal((await preview(limited.code, shoppers[3].cookie)).status, 400)
  await write(`/api/admin/vouchers/${limited.id}`, { expiresAt, maxUses: 4 })
  assert.equal((await checkout(limited.code, shoppers[3].cookie)).status, 201, 'Extending expiry and quota reopens the code')
  const parallel = await create({ maxUses: 1 })
  const simultaneous = await Promise.all(shoppers.slice(0, 2).map((shopper, index) => checkout(parallel.code, shopper.cookie, '/api/orders', index ? extra.id : product.id)))
  assert.deepEqual(simultaneous.map(result => result.status).sort(), [201, 400], 'Parallel requests cannot exceed quota')
  const once = await create({ maxUses: 10 })
  const duplicate = await Promise.all([checkout(once.code, shoppers[0].cookie), checkout(once.code, shoppers[0].cookie, '/api/orders', extra.id)])
  assert.deepEqual(duplicate.map(result => result.status).sort(), [201, 400], 'Parallel requests from one account only redeem once')
  const reserved = await create({ maxUses: 1 })
  const pending = await checkout(reserved.code, shoppers[0].cookie, '/api/payments/vnpay/checkout')
  assert.equal(pending.status, 201)
  assert.equal((await listed(reserved.code)).reservedCount, 1)
  assert.equal((await preview(reserved.code, shoppers[1].cookie)).status, 400)
  await db.cancelUnpaidVnpayOrder({ orderId: pending.data.orderId })
  assert.equal((await listed(reserved.code)).usedCount, 0)
  assert.equal((await preview(reserved.code, shoppers[0].cookie)).status, 200)
  assert.equal((await checkout(reserved.code, shoppers[1].cookie)).status, 201, 'Cancelled unpaid online order returns quota')
  const failed = await create({ maxUses: 1 })
  fake.failSession = true
  assert.equal((await checkout(failed.code, shoppers[0].cookie, '/api/payments/stripe/checkout')).status, 502)
  fake.failSession = false
  assert.equal((await listed(failed.code)).usedCount, 0)
  assert.equal((await checkout(failed.code, shoppers[0].cookie)).status, 201, 'Gateway failure permits retry by the same account')
  const restore = await create({ maxUses: 2 })
  const cancelled = await checkout(restore.code, shoppers[0].cookie)
  await db.updateOrderStatus(cancelled.data.id, 'cancelled')
  const replacement = await checkout(restore.code, shoppers[0].cookie)
  assert.equal(replacement.status, 201)
  await assert.rejects(db.updateOrderStatus(cancelled.data.id, 'pending'), /Mỗi tài khoản/, 'Restoring cancelled orders cannot bypass one use per account')
  await db.updateOrderStatus(replacement.data.id, 'delivered')
  await db.updateOrderStatus(replacement.data.id, 'cancelled')
  assert.equal((await preview(restore.code, shoppers[0].cookie)).status, 400, 'Paid cancelled orders retain redemption history')
  const expired = await create({ expiresAt: new Date(Date.now() - 1000).toISOString() })
  assert.equal((await checkout(expired.code, shoppers[4].cookie)).status, 400)
  const changed = await create({ maxUses: 1, expiresAt })
  assert.equal((await preview(changed.code, shoppers[4].cookie)).status, 200)
  await write(`/api/admin/vouchers/${changed.id}`, { expiresAt: new Date(Date.now() - 1000).toISOString() })
  assert.equal((await checkout(changed.code, shoppers[4].cookie)).status, 400, 'Expiry is rechecked after the preview')
  console.log('PASS voucher rules: editable quota/expiry, per-account reuse, parallel requests (single-connection pool), online reservation/release, failed gateway retry, cancelled/paid history and restore protection.')
}
