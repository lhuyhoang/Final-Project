CREATE TABLE staff_roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL CHECK (LENGTH(BTRIM(name)) BETWEEN 2 AND 60),
  permissions JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT staff_roles_permissions_valid CHECK (
    JSONB_TYPEOF(permissions) = 'array'
    AND JSONB_ARRAY_LENGTH(permissions) BETWEEN 1 AND 8
    AND permissions <@ '["overview", "inventory", "products", "categories", "showrooms", "orders", "online-payments", "settings"]'::jsonb
  )
);
CREATE UNIQUE INDEX staff_roles_name_key ON staff_roles (LOWER(BTRIM(name)));
ALTER TABLE users ADD COLUMN staff_role_id INTEGER REFERENCES staff_roles(id) ON DELETE RESTRICT;
ALTER TABLE users DROP CONSTRAINT users_role_valid;
ALTER TABLE users ADD CONSTRAINT users_role_valid CHECK (role IN ('admin', 'staff', 'customer'));
ALTER TABLE users ADD CONSTRAINT users_staff_role_valid CHECK (
  (role = 'staff' AND staff_role_id IS NOT NULL) OR (role <> 'staff' AND staff_role_id IS NULL)
);
CREATE INDEX users_staff_role_id_idx ON users (staff_role_id) WHERE staff_role_id IS NOT NULL;
