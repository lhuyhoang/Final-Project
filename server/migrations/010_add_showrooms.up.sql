CREATE TABLE showrooms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  address VARCHAR(250) NOT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  opening_hours VARCHAR(120) NOT NULL DEFAULT '',
  map_url VARCHAR(500) NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT showrooms_name_not_blank CHECK (BTRIM(name) <> ''),
  CONSTRAINT showrooms_address_not_blank CHECK (BTRIM(address) <> ''),
  CONSTRAINT showrooms_sort_order_valid CHECK (sort_order >= 0)
);

CREATE INDEX showrooms_active_sort_idx
  ON showrooms (is_active, sort_order, id);
