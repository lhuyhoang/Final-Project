CREATE TABLE product_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  icon VARCHAR(40) NOT NULL DEFAULT 'Box',
  color VARCHAR(20) NOT NULL DEFAULT '#edf0ff',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT product_categories_name_not_blank CHECK (BTRIM(name) <> ''),
  CONSTRAINT product_categories_icon_not_blank CHECK (BTRIM(icon) <> ''),
  CONSTRAINT product_categories_color_not_blank CHECK (BTRIM(color) <> '')
);

CREATE UNIQUE INDEX product_categories_name_lower_key ON product_categories (LOWER(name));
CREATE INDEX product_categories_created_at_idx ON product_categories (created_at DESC, id ASC);

