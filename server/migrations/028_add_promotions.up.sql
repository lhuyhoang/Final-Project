CREATE TABLE vouchers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(24) NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9]{6,24}$'),
  amount BIGINT NOT NULL CHECK (amount BETWEEN 1 AND 1000000000),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE orders ADD COLUMN voucher_code VARCHAR(24);
ALTER TABLE orders ADD COLUMN discount_amount BIGINT NOT NULL DEFAULT 0 CHECK (discount_amount >= 0);
ALTER TABLE staff_roles DROP CONSTRAINT staff_roles_permissions_valid;
ALTER TABLE staff_roles ADD CONSTRAINT staff_roles_permissions_valid CHECK (
  JSONB_TYPEOF(permissions) = 'array'
  AND JSONB_ARRAY_LENGTH(permissions) BETWEEN 1 AND 9
  AND permissions <@ '["overview", "inventory", "products", "categories", "showrooms", "orders", "online-payments", "settings", "promotions"]'::jsonb
);
